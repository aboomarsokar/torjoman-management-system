import { describe, expect, it } from 'vitest'
import { bankRecords, planBank } from './readingBank'

const HEAD = ['المقرّر', 'السؤال', 'أ', 'ب', 'ج', 'د', 'الإجابة']
const plan = (rows: string[][], units = [1, 2]) => planBank(bankRecords([HEAD, ...rows]), units)

describe('بنك أسئلة القراءة', () => {
  it('يقرأ السطر الصحيح ويحوّل الإجابة إلى مفتاح', () => {
    const p = plan([['1', 'متى؟', 'أمس', 'اليوم', 'غداً', 'أبداً', 'ج']])
    expect(p.errors).toEqual([])
    expect(p.rows[0]).toMatchObject({ line: 2, unitOrder: 1, body: 'متى؟', correct: 2 })
    expect(p.perUnit.get(1)).toBe(1)
  })

  it('يقبل الإجابة رقماً عربياً أو لاتينياً أو حرفاً إنجليزياً', () => {
    const p = plan([
      ['١', 'س1', 'أ1', 'ب1', 'ج1', 'د1', '٤'],
      ['2', 'س2', 'أ2', 'ب2', 'ج2', 'د2', 'B']
    ])
    expect(p.rows.map(r => [r.unitOrder, r.correct])).toEqual([[1, 3], [2, 1]])
  })

  it('يرفض كلّ خطأٍ برسالته وسطره', () => {
    const p = plan([
      ['9', 'س', 'أ', 'ب', 'ج', 'د', 'أ'],
      ['1', '', 'أ', 'ب', 'ج', 'د', 'أ'],
      ['1', 'س', 'أ', '', 'ج', 'د', 'أ'],
      ['1', 'س', 'نعم', 'نعم', 'ج', 'د', 'أ'],
      ['1', 'س', 'أ', 'ب', 'ج', 'د', 'هـ'],
      ['1', 'مكرّر', 'أ', 'ب', 'ج', 'د', 'أ'],
      ['1', 'مكرّر', 'أ', 'ب', 'ج', 'د', 'ب']
    ])
    expect(p.errors).toEqual([
      { line: 2, message: 'المقرّر 9 غير موجود في المنصّة' },
      { line: 3, message: 'السؤال فارغ' },
      { line: 4, message: 'أحد الخيارات الأربعة فارغ' },
      { line: 5, message: 'خياران متطابقان' },
      { line: 6, message: 'الإجابة غير مفهومة — اكتب أ أو ب أو ج أو د، أو نصَّ الخيار الصحيح كما هو' },
      { line: 8, message: 'السؤال مكرّر في المقرّر نفسه' }
    ])
    expect(p.rows).toHaveLength(1)
  })

  it('شكلُ بنك المستخدم: «رقم المقرّر» بالشدّة، و«الخيار 1…4»، والإجابةُ نصُّ الخيار، وعمودٌ زائد', () => {
    const p = planBank(bankRecords([
      ['رقم المقرّر', 'السؤال', 'الخيار 1', 'الخيار 2', 'الخيار 3', 'الخيار 4', 'الإجابة الصحيحة', 'المرجع'],
      ['1', 'يصف المؤلف كتابه بأنه فصول', 'مدرسة الوعظ', 'مدرسة التزكية', 'مدرسة الترغيب والترهيب', 'مدرسة الرقائق', 'مدرسة الترغيب والترهيب', 'ص 6'],
      ['2', 'س', 'خ1', 'خ2', 'خ3', 'خ4', 'نصٌّ ليس خياراً', 'ص 9']
    ]), [1, 2])
    expect(p.rows[0]).toMatchObject({ unitOrder: 1, correct: 2 })
    expect(p.errors).toEqual([{ line: 3, message: 'الإجابة غير مفهومة — اكتب أ أو ب أو ج أو د، أو نصَّ الخيار الصحيح كما هو' }])
  })

  it('يتجاهل الأسطر الفارغة تماماً', () => {
    expect(plan([['', '', '', '', '', '', ''], ['1', 'س', 'أ', 'ب', 'ج', 'د', 'د']]).rows).toHaveLength(1)
  })
})
